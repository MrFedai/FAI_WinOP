<#
.SYNOPSIS
    Generates the "What the fedai profile does" section of README.md from the profile, tweak and app data.

.DESCRIPTION
    Called without parameters: builds the production bundle in a temporary folder, loads profiles/fedai.json, the tweak
    catalog (tweaks/**/*.psd1) and apps/catalog.json, rewrites the region between the markers
    <!-- profile:fedai:begin --> and <!-- profile:fedai:end --> in README.md, and prints what it did.
    The fixed flow steps are text in this script; the tweak list, apps and layout summary come from the data.
    The order follows the real run order in src/Engine.ps1: First tweaks, apps, the other tweaks in profile order,
    games, layout, shell refresh. If the region did not change, the file is not touched.

.PARAMETER Check
    Check only: exits with 1 if the README region is out of date (CI). No file is written.

.PARAMETER ProfilePath
    Profile file (default: profiles/fedai.json). Used by tests.

.PARAMETER ReadmePath
    README file (default: README.md). Used by tests.

.EXAMPLE
    pwsh -NoProfile -File build/ProfileDoc.ps1
    pwsh -NoProfile -File build/ProfileDoc.ps1 -Check
#>
[CmdletBinding()]
param(
    [switch] $Check,
    [string] $ProfilePath = '',
    [string] $ReadmePath = ''
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $ProfilePath) { $ProfilePath = Join-Path (Join-Path $repoRoot 'profiles') 'fedai.json' }
if (-not $ReadmePath) { $ReadmePath = Join-Path $repoRoot 'README.md' }
$beginMark = '<!-- profile:fedai:begin -->'
$endMark = '<!-- profile:fedai:end -->'

# Bundle'daki sınıflar yalnız nokta-kaynak yapılan kapsamda görünür.
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ('fai-profiledoc-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tmp -Force | Out-Null
try {
    $bundle = Join-Path $tmp 'install.ps1'
    & (Join-Path $PSScriptRoot 'Bundle.ps1') -OutFile $bundle 6>&1 | Out-Null
    . $bundle
    $catalog = Import-FaiTweakCatalog -Path (Join-Path $repoRoot 'tweaks')
    $apps = Import-FaiAppCatalog -Path (Join-Path (Join-Path $repoRoot 'apps') 'catalog.json')
    $prof = Import-FaiProfileFile -Path $ProfilePath
}
finally { Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue }

function ConvertTo-MdText([string] $Text) {
    return ($Text -replace '([\\*_`|<>\[\]])', '\$1')
}

function Format-ParamText([hashtable] $Params) {
    if ($null -eq $Params -or $Params.Count -eq 0) { return '' }
    return ' (' + ((@($Params.Keys | Sort-Object | ForEach-Object { '`{0} = {1}`' -f $_, [string]$Params[$_] })) -join ', ') + ')'
}

function Format-TweakLine([object] $Entry) {
    $id = [string]$Entry['Id']
    if (-not $catalog.ContainsKey($id)) { throw "Profile tweak is not in the catalog: $id" }
    $t = $catalog[$id]
    $line = '- ' + (ConvertTo-MdText $t.Title) + (Format-ParamText $Entry['Params']) + ' · `' + $id + '`'
    $notes = New-Object 'System.Collections.Generic.List[string]'
    if ($t.Conditions.Count -gt 0) { $notes.Add('only if ' + (ConvertTo-MdText ((@($t.Conditions | ForEach-Object { $_.Describe() })) -join ' and '))) }
    if ($t.AlwaysConfirm) { $notes.Add('asks every run, skipped with `-Unattended`') }
    elseif ($t.Risk -eq 'Caution') { $notes.Add('asks for confirmation') }
    elseif ($t.Risk -eq 'Risk') { $notes.Add('asks you to type `YES`') }
    if ($notes.Count -gt 0) { $line += ' — ' + ($notes -join '; ') }
    return $line
}

function Test-FirstEntry([object] $Entry) {
    $id = [string]$Entry['Id']
    return ($catalog.ContainsKey($id) -and $catalog[$id].First)
}

$lines = New-Object 'System.Collections.Generic.List[string]'
$entries = @($prof.Tweaks)
$firstEntries = @($entries | Where-Object { Test-FirstEntry $_ })
$restEntries = @($entries | Where-Object { -not (Test-FirstEntry $_) })

$lines.Add($beginMark)
$lines.Add('<!-- Generated by build/ProfileDoc.ps1 from profiles/fedai.json, tweaks/ and apps/catalog.json. Do not edit by hand. -->')
$lines.Add('')
$lines.Add('When you run the profile, this is what happens, in this order:')
$lines.Add('')
$lines.Add('1. **Elevation and user check.** The tool needs an administrator PowerShell (`-DryRun` too). If it was not started elevated, it asks for UAC and restarts itself. If the elevated account is not the owner of the desktop session, it stops (exit code 3) and names both accounts; `-AllowOtherUser` continues on purpose. If the session owner cannot be found, it warns and continues.')
$lines.Add('2. **Data folder and log.** The data folder under `%ProgramData%` is checked (only SYSTEM and Administrators may write); untrusted items are moved aside. A log file for the run is created and its path is printed.')
$n = 3
if ($firstEntries.Count -gt 0) {
    $lines.Add(('{0}. **First steps** (before apps and the other tweaks):' -f $n))
    $n++
    foreach ($e in $firstEntries) { $lines.Add('   ' + (Format-TweakLine $e)) }
}
$lines.Add(('{0}. **Snapshots.** Before every change the current state is saved to a backup session; `-Undo` uses it. With `-DryRun` nothing is written, nothing is saved, and the planned changes are only listed.' -f $n))
$n++
$appEntries = @($prof.Apps)
if ($appEntries.Count -gt 0) {
    $lines.Add(('{0}. **Apps** ({1}, from `apps/catalog.json`). Each is installed if missing; autostart entries and desktop shortcuts of the installers are removed and Start menu folders are flattened, except where the profile keeps autostart. Apps in the profile are protected from the bloat removal below.' -f $n, $appEntries.Count))
    $n++
    foreach ($a in $appEntries) {
        $id = [string]$a['Id']
        if (-not $apps.ContainsKey($id)) { throw "Profile app is not in the catalog: $id" }
        $line = '   - ' + (ConvertTo-MdText ([string]$apps[$id]['name'])) + ' · ' + [string]$apps[$id]['source'] + ' · `' + $id + '`'
        if ([bool]$a['KeepAutostart']) { $line += ' — autostart kept' }
        $lines.Add($line)
    }
}
if ($restEntries.Count -gt 0) {
    $lines.Add(('{0}. **Tweaks** ({1}), in profile order, grouped by category. A tweak whose target state is already in place is skipped, and so is one whose condition does not match this machine. Caution tweaks ask for confirmation (`Y` / `N`); tweaks marked `Risk` ask you to type `YES`.' -f $n, $restEntries.Count))
    $n++
    $run = ''
    foreach ($e in $restEntries) {
        $cat = [string]$catalog[[string]$e['Id']].Category
        if ($cat -ne $run) {
            $lines.Add('   - **' + $cat + '**')
            $run = $cat
        }
        $lines.Add('     ' + (Format-TweakLine $e))
    }
}
if (@($prof.Games).Count -gt 0) {
    $lines.Add(('{0}. **Games** ({1}): per-game CPU priority and processor affinity.' -f $n, @($prof.Games).Count))
    $n++
}
$layout = $prof.Layout
if ($null -ne $layout -and $layout.Count -gt 0) {
    $lines.Add(('{0}. **Taskbar, desktop and Start layout** (the profile''s `layout` section):' -f $n))
    $n++
    if ($layout.Contains('taskbar')) {
        $tb = $layout['taskbar']
        $parts = New-Object 'System.Collections.Generic.List[string]'
        if ($tb.Contains('alignment')) { $parts.Add('alignment `' + [string]$tb['alignment'] + '`') }
        if ($tb.Contains('autoHide')) {
            if ([bool]$tb['autoHide']) { $parts.Add('auto-hide on') } else { $parts.Add('auto-hide off') }
        }
        $lines.Add('   - Taskbar: ' + ($parts -join ', '))
        if ($tb.Contains('pins')) {
            $names = @($tb['pins'] | ForEach-Object {
                    if ($_.Contains('appId')) { [string]$_['appId'] }
                    else { [System.IO.Path]::GetFileNameWithoutExtension(([string]$_['link']).Replace('\', '/').Split('/')[-1]) }
                })
            $lines.Add(('   - Taskbar pins ({0}): {1}' -f $names.Count, ((@($names | ForEach-Object { '`' + $_ + '`' })) -join ', ')))
        }
    }
    if ($layout.Contains('desktopIcons')) {
        $icons = $layout['desktopIcons']
        $shown = @($icons.Keys | Sort-Object | Where-Object { [bool]$icons[$_] })
        $hidden = @($icons.Keys | Sort-Object | Where-Object { -not [bool]$icons[$_] })
        $lines.Add('   - Desktop icons shown: ' + ((@($shown | ForEach-Object { '`' + $_ + '`' })) -join ', ') + '; hidden: ' + ((@($hidden | ForEach-Object { '`' + $_ + '`' })) -join ', '))
    }
    if ($layout.Contains('desktop')) {
        $d = $layout['desktop']
        if ($d.Contains('iconSize')) { $lines.Add(('   - Desktop icon size: {0}' -f [string]$d['iconSize'])) }
    }
    if ($layout.Contains('start')) { $lines.Add('   - Start menu layout: restored from the profile (`start2.bin`)') }
}
$lines.Add(('{0}. **Shell refresh.** Explorer, desktop and Start are refreshed once at the end, so the new look appears without signing out.' -f $n))
$n++
$lines.Add(('{0}. **Report and restart.** A summary lists every item as applied, up to date, skipped or failed (exit code 1 if anything failed). The tool does not restart Windows by itself. If a step needs a restart (for example Windows updates), the run stops there; after the restart the resume command continues the same session through `RunOnce`, or you run the same command again.' -f $n))
$lines.Add('')
$lines.Add('### Undo and what cannot be undone')
$lines.Add('')
$lines.Add('`-Undo` reverts the last session in reverse order (`-Undo -DryRun` previews it; `-Undo -Session <id>` picks a session; `-SkipFailed` closes a session whose remaining entries cannot be reverted). Apps installed in that run are uninstalled; changed settings, services, tasks, files and layout are restored from the snapshots.')
$lines.Add('')
$lines.Add('Not reverted by `-Undo`:')
$lines.Add('')
$lines.Add('- Creating the System Restore point (the point itself stays).')
$lines.Add('- Windows updates that were installed, and any restart.')
$lines.Add('- The default browser: it is set by hand in Settings, so it is reverted by hand too.')
$irreversible = @($entries | Where-Object { $catalog.ContainsKey([string]$_['Id']) -and $catalog[[string]$_['Id']].Confirm -match 'cannot be undone' })
foreach ($e in $irreversible) {
    $t = $catalog[[string]$e['Id']]
    $lines.Add('- ' + (ConvertTo-MdText $t.Title) + ' (`' + [string]$e['Id'] + '`): ' + (ConvertTo-MdText $t.Confirm))
}
$lines.Add($endMark)
$region = ($lines -join "`n")

$readme = [System.IO.File]::ReadAllText($ReadmePath) -replace "`r`n", "`n"
$b = $readme.IndexOf($beginMark, [System.StringComparison]::Ordinal)
$e = $readme.IndexOf($endMark, [System.StringComparison]::Ordinal)
if ($b -lt 0 -or $e -lt $b) { throw "README markers not found: $beginMark ... $endMark" }
$content = $readme.Substring(0, $b) + $region + $readme.Substring($e + $endMark.Length)

$upToDate = ($readme -ceq $content)
$summary = '{0} tweaks, {1} apps' -f $entries.Count, $appEntries.Count
$name = Split-Path -Leaf $ReadmePath

if ($Check) {
    if ($upToDate) { Write-Host "$name profile section is up to date ($summary)."; exit 0 }
    Write-Host "$name profile section is out of date: run 'pwsh -NoProfile -File build/ProfileDoc.ps1' and commit." -ForegroundColor Red
    exit 1
}
if ($upToDate) { Write-Host "$name profile section is already up to date ($summary)."; exit 0 }
# .md: UTF-8 BOM'suz, LF (.gitattributes).
[System.IO.File]::WriteAllText($ReadmePath, $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "$name profile section written ($summary)."
